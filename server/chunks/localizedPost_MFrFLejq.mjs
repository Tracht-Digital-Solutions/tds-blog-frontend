	return {
		post: {
			...src,
			lang,
			title: title ?? src.title,
			excerpt: excerpt ?? src.excerpt
		},
		bodyHtml: bodyHtml ?? srcHtml,
		blocks: null,
		translated: ok,
		sourceLang: other
	};
