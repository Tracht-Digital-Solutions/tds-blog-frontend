async function renderBlockHtml(block, lang = "de") {
	switch (block.type) {
		case "heading": return `<h${block.level} id="${slugify(block.text)}">${inline(block.text)}</h${block.level}>`;
		case "paragraph": return block.text.trim() === "" ? "" : `<p>${inline(block.text)}</p>`;
		case "list": {
			const items = block.items.filter((i) => i.trim() !== "").map((i) => `<li>${inline(i)}</li>`).join("");
			if (items === "") return "";
			const tag = block.ordered ? "ol" : "ul";
			return `<${tag}>${items}</${tag}>`;
		}
		case "quote": return `<blockquote><p>${inline(block.text)}</p>${block.cite ? `<cite>${esc(block.cite)}</cite>` : ""}</blockquote>`;
		case "code": return renderMarkdown("```" + (block.lang || "text") + "\n" + block.code + "\n```");
		case "image": return block.url ? `<figure><img src="${esc(block.url)}" alt="${esc(block.alt)}" loading="lazy" />${block.caption ? `<figcaption>${esc(block.caption)}</figcaption>` : ""}</figure>` : "";
		case "divider": return `<hr />`;
		case "callout": return `<div class="tds-callout tds-callout--${block.variant}">${inline(block.text)}</div>`;
		case "button": return block.href ? `<p class="tds-block-button"><a class="btn btn-${block.style}" href="${esc(block.href)}">${esc(block.label || "")}</a></p>` : "";
		case "video": {
			const id = block.provider === "youtube" ? youtubeId(block.url) : vimeoId(block.url);
			if (!id) return "";
			const src = block.provider === "youtube" ? `https://www.youtube-nocookie.com/embed/${id}` : `https://player.vimeo.com/video/${id}`;
			const provider = block.provider === "youtube" ? "YouTube" : "Vimeo";
			const t = EMBED_TEXT[lang];
			return `<div class="tds-video-embed consent-placeholder" data-consent-embed="marketing" data-embed-src="${esc(src)}" data-embed-title="${esc(provider)}"><p class="consent-placeholder__title">${esc(t.title)}</p><p class="consent-placeholder__body">${esc(t.body(provider))}</p><div class="consent-placeholder__actions"><button type="button" class="btn btn-primary" data-embed-load hidden>${esc(t.load)}</button><button type="button" class="btn btn-ghost" data-embed-settings hidden>${esc(t.settings)}</button><a class="btn btn-ghost" href="${esc(block.url)}" target="_blank" rel="noopener noreferrer">${esc(t.open(provider))}</a></div></div>`;
		}
		default: return "";
	}
}
/**
* Render a whole block document to a single HTML string (embeds inlined as
* static markup, ads skipped). Used by the print view, which has no room for
* live ad components.
*/
async function renderBlocksToHtml(blocks, snippets = [], lang = "de") {
	const out = [];
	for (const block of blocks) {
		if (block.type === "adsense") continue;
		if (block.type === "custom") {
			const s = snippets.find((x) => x.id === block.snippetId);
			if (!s) continue;
			if (s.kind === "embed" && typeof s.definition.html === "string") out.push(s.definition.html);
			else if (s.kind === "preset" && typeof s.definition.type === "string") out.push(await renderBlockHtml(s.definition, lang));
			continue;
		}
		out.push(await renderBlockHtml(block, lang));
	}
	return out.join("\n");
}
